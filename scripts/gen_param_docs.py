"""
Generate docs/PARAMETERS.md from the effect specs and Look inputs.

    python scripts/gen_param_docs.py        (needs the bpy module)
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import gold_extended.effects  # noqa: E402,F401
from gold_extended.core import brushes, grade, params, registry, shading  # noqa: E402


def fmt(v):
    if isinstance(v, float):
        return f'{v:g}'
    if isinstance(v, (tuple, list)):
        return '(' + ', '.join(fmt(x) for x in v) + ')'
    if v is None or v == '':
        return '–'
    return str(v)


def rng(p):
    if p.min is None and p.max is None:
        return ''
    return f'{fmt(p.min)} … {fmt(p.max)}'


def main():
    out = ['# Parameter Reference', '',
           '_Generated by `scripts/gen_param_docs.py` from the effect specs – do not edit by hand._', '',
           '⚙ = advanced parameter, shown when **Advanced** is enabled in the Effect panel.', '']
    out += ['## Effects', '']
    for eff in registry.EFFECTS.values():
        out += [f'### {eff.label}', '', eff.description + '.', '',
                f'*Host:* `{eff.host}` – ' + ('the object\'s own mesh is the domain/shape.' if eff.host == 'DOMAIN'
                                               else 'references a surface mesh (selected mesh, or a new one).'),
                '', f'*Create buttons:* ' + ', '.join(f'**{v.label}** ({v.preset})' for v in eff.variants), '',
                f'*Presets:* ' + ', '.join(f'`{n}`' for n in eff.presets), '',
                '*Materials:* ' + ', '.join(f'{s.role} (brush: {s.brush or "none"})' for s in eff.materials), '']
        for panel in eff.spec:
            rows = [p for p in panel.params if not p.hidden]
            if not rows:
                continue
            out += [f'**{panel.name}**' + (f' – {panel.desc}' if panel.desc else ''), '',
                    '| Parameter | Type | Default | Range | Description |', '|---|---|---|---|---|']
            for p in rows:
                desc = (p.desc or '').replace('|', '\\|')
                name = f'{p.name} ⚙' if p.advanced else p.name
                out.append(f'| {name} | {p.type.lower()}{"/" + p.subtype.lower() if p.subtype else ""} '
                           f'| {fmt(p.default)} | {rng(p)} | {desc} |')
            out.append('')
    out += ['## Look (material) controls', '',
            'Every Gold FX material has one *Look* node; its inputs are drawn in the **Look** panel.', '',
            '| Group | Control | Default | Range | Description |', '|---|---|---|---|---|']
    for nm, _t, d, lo, hi, panel, desc in shading.LOOK_INPUTS:
        out.append(f'| {panel} | {nm} | {fmt(d)} | {fmt(lo)} … {fmt(hi)} | {desc} |')
    out += ['', '### Look presets', '', '| Preset | Settings |', '|---|---|']
    for n, v in shading.LOOK_PRESETS.items():
        out.append(f'| {n} | ' + (', '.join(f'{k} {fmt(x)}' for k, x in v.items()) or 'defaults') + ' |')
    out += ['', '## Scene Grade (compositor)', '', '| Control | Default | Range | Description |', '|---|---|---|---|']
    for nm, d, lo, hi, desc in grade.GRADE_INPUTS:
        out.append(f'| {nm} | {fmt(d)} | {fmt(lo)} … {fmt(hi)} | {desc} |')
    out += ['', '## Built-in brush styles', '', '| Style | Type | Inputs |', '|---|---|---|']
    for name, (typ, _b, inputs) in brushes.BUILTIN.items():
        out.append(f'| {name} | {typ} | ' + ', '.join(f'{i[0]} ({fmt(i[1])})' for i in inputs) + ' |')
    out.append('')
    path = os.path.join(ROOT, 'docs', 'PARAMETERS.md')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
    n = sum(1 for e in registry.EFFECTS.values() for _ in params.iter_params(e.spec))
    print(f'wrote {path}: {len(registry.EFFECTS)} effects, {n} parameters')


if __name__ == '__main__':
    main()
    sys.stdout.flush()
    os._exit(0)
